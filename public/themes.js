window.buildConfig = function (cfg) {
  const theme = window.THEMES[cfg && cfg.theme] ? cfg.theme : "simple";
  return Object.assign(
    {},
    window.COMMON_DEFAULTS,
    window.THEMES[theme].defaults,
    cfg || {},
    { theme }
  );
};
